def verify(root: Path) -> int:
    print("=" * 78)
    print(f"VERIFY {UPDATER_NAME}")
    print("=" * 78)

    missing = [rel for rel in GENERATED_FILES if not (root / rel).exists()]
    if missing:
        print("[FAIL] Missing generated files:")
        for rel in missing:
            print(f"  - {rel}")
        return 2

    router_text = (root / ROUTER_REL).read_text(encoding="utf-8")
    patched, _ = patch_router_text(router_text)
    if patched != router_text:
        print("[FAIL] API router is not fully patched.")
        return 2

    try:
        _compile_generated(root)
        print("[OK] Python syntax compile")
    except Exception as exc:
        print(f"[FAIL] Python compile: {exc}")
        return 3

    env = os.environ.copy()
    env["PYTHONPATH"] = str(root) + os.pathsep + env.get("PYTHONPATH", "")
    proc = subprocess.run(
        [sys.executable, "-c", _smoke_script()],
        cwd=str(root),
        env=env,
        text=True,
        capture_output=True,
    )
    if proc.stdout:
        print(proc.stdout.rstrip())
    if proc.returncode != 0:
        if proc.stderr:
            print(proc.stderr.rstrip())
        print("[FAIL] Runtime smoke test")
        return proc.returncode or 4

    try:
        subprocess.run(
            [
                sys.executable,
                "-c",
                "from app.api.v1.api import api_router; "
                "assert any(getattr(r, 'path', '').startswith('/image-lab') for r in api_router.routes); "
                "print('IMAGE_LAB_ROUTER_OK')",
            ],
            cwd=str(root),
            env=env,
            text=True,
            check=True,
        )
    except subprocess.CalledProcessError:
        print("[WARN] Core runtime passed, but importing the full API router failed.")
        print("       This can be caused by unrelated existing application dependencies.")
        return 5

    print("[OK] Image Processing LAB Backend v0.1 verified.")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=UPDATER_NAME)
    parser.add_argument("--project", default=None, help="Lambda Vision Backend project root")

    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("scan")
    apply_parser = sub.add_parser("apply")
    apply_parser.add_argument("--force", action="store_true")
    sub.add_parser("verify")

    args = parser.parse_args()
    root = find_project_root(args.project)

    if args.command == "scan":
        return scan(root)
    if args.command == "apply":
        return apply(root, force=args.force)
    if args.command == "verify":
        return verify(root)
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
