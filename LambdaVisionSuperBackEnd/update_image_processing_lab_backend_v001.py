def patch_router_text(text: str) -> tuple[str, list[str]]:
    changes: list[str] = []
    if "image_lab_api" not in text:
        anchor = "from app.api.v1.endpoints import "
        lines = text.splitlines()
        inserted = False
        for idx, line in enumerate(lines):
            if line.startswith(anchor):
                lines.insert(idx + 1, "from app.api.v1.endpoints import image_lab_api")
                inserted = True
                changes.append("import image_lab_api")
                break
        if not inserted:
            # Conservative fallback after APIRouter import.
            for idx, line in enumerate(lines):
                if line.strip() == "from fastapi import APIRouter":
                    lines.insert(idx + 1, "from app.api.v1.endpoints import image_lab_api")
                    inserted = True
                    changes.append("import image_lab_api")
                    break
        if not inserted:
            raise RuntimeError("Could not find a safe import anchor in app/api/v1/api.py")
        text = "\n".join(lines) + ("\n" if text.endswith("\n") else "")

    route_line = (
        'api_router.include_router('
        'image_lab_api.router, prefix="/image-lab", tags=["Image Processing LAB"])'
    )
    if route_line not in text:
        lines = text.splitlines()
        insert_after = None
        for idx, line in enumerate(lines):
            if "api_router.include_router(" in line:
                insert_after = idx
        if insert_after is None:
            raise RuntimeError("Could not find api_router.include_router(...) anchor")
        lines.insert(insert_after + 1, route_line)
        changes.append("mount /image-lab router")
        text = "\n".join(lines) + ("\n" if text.endswith("\n") else "")

    return text, changes


def status_for_generated(root: Path) -> list[tuple[str, str]]:
    rows: list[tuple[str, str]] = []
    for rel, desired in GENERATED_FILES.items():
        path = root / rel
        if not path.exists():
            rows.append((rel, "CREATE"))
        else:
            current = path.read_text(encoding="utf-8")
            rows.append((rel, "OK" if current == desired else "DIFFERENT"))
    return rows


def scan(root: Path) -> int:
    print("=" * 78)
    print(UPDATER_NAME)
    print("=" * 78)
    print(f"Project : {root}")
    print(f"Router  : {root / ROUTER_REL}")
